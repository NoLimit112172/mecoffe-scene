def build_export(root=ROOT, *, source_commit=None):
    root=Path(root)
    payload={}
    inputs={}
    for name in input_paths():
        path=root/name
        if path.is_symlink():
            raise ValueError('Source symlink is not supported: '+name)
        raw=path.read_bytes()
        policy='raw' if name.startswith(ASSETS) else 'lf'
        normalized=raw if policy=='raw' else lf(raw)
        inputs[name]={'sha256':sha(normalized),'byte_policy':policy}
        if name.startswith(SERVICE):
            filename=name[len(SERVICE):]
            value=runtime_module(Path(filename).stem,normalized) if filename.endswith('.py') else normalized
            payload[f'src/{IMPORT_NAME}/{filename}']=value
        elif name.endswith('/asset_library.py'):
            payload[f'src/{IMPORT_NAME}/_asset_library.py']=normalized
        elif name.startswith(ASSETS):
            payload[f'src/{IMPORT_NAME}/resources/mecoffe-embed-v1/{Path(name).name}']=raw
        else:
            payload['NOTICE.md']=normalized
    # Check source contracts and the pinned published catalog before generating anything.
    for filename,version in [('contract.json','scene.result.v1'),('contract-v2.json','scene.result.v2')]:
        if json.loads(payload[f'src/{IMPORT_NAME}/{filename}'])['properties']['schema_version']['const']!=version:
            raise ValueError('Review the supported contract version constants')
    resource=f'src/{IMPORT_NAME}/resources/mecoffe-embed-v1/'
    descriptor=json.loads(payload[resource+'asset-library.json'])
    if sha(payload[resource+'catalog.json'])!=descriptor['catalog_sha256']:
        raise ValueError('Published catalog bytes differ from the registered descriptor')
    payload.update({'pyproject.toml':pyproject(),'VERSION':(VERSION+'\n').encode('utf-8'),
                    'README.md':readme(),'verify_export.py':VERIFY_SOURCE.encode('utf-8'),
                    f'src/{IMPORT_NAME}/__init__.py':public_init()})
    manifest={'schema_version':'scene.service-export.v1','package':{'name':DISTRIBUTION,'import_name':IMPORT_NAME,
              'version':VERSION,'requires_python':REQUIRES_PYTHON},
              'source_commit':source_commit or source_revision(root),'inputs':inputs,
              'exporter':{'version':EXPORTER_VERSION,'sha256':sha(lf((root/'scripts/export_scene_service.py').read_bytes()))},
              'files':{name:sha(raw) for name,raw in sorted(payload.items())}}
    payload[MANIFEST]=json_bytes(manifest)
    return payload


def check_export(out, expected):
    out=Path(out)
    actual={p.relative_to(out).as_posix():p for p in out.rglob('*') if p.is_file() or p.is_symlink()}
    missing=sorted(set(expected)-set(actual));extra=sorted(set(actual)-set(expected))
    changed=sorted(name for name in set(expected)&set(actual)
                   if actual[name].is_symlink() or actual[name].read_bytes()!=expected[name])
    if missing or extra or changed:
        raise ValueError(f'导出目录不一致：缺失={missing}；新增={extra}；内容变化={changed}')
    return {'ok':True,'version':VERSION,'files':len(expected)}


def write_export(out, expected):
    out=Path(out)
    extra={p.relative_to(out).as_posix() for p in out.rglob('*') if p.is_file() or p.is_symlink()}-set(expected)
    if extra:
        raise ValueError('拒绝删除导出目录额外文件，请先检查：'+str(sorted(extra)))
    for name,raw in expected.items():
        target=out/name
        if target.is_symlink():
            raise ValueError('Export symlink is not supported: '+name)
        target.parent.mkdir(parents=True,exist_ok=True)
        target.write_bytes(raw)
    return check_export(out,expected)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out',type=Path,default=DEFAULT_OUT)
    parser.add_argument('--check',action='store_true',help='Compare against source without writing')
    args=parser.parse_args()
    try:
        expected=build_export()
        result=check_export(args.out,expected) if args.check else write_export(args.out,expected)
        print(json.dumps(result,ensure_ascii=False))
        return 0
    except (OSError,ValueError,KeyError,subprocess.CalledProcessError) as error:
        print(str(error),file=sys.stderr)
        return 1


if __name__=='__main__':
    sys.exit(main())
