ASSETS = 'adapter/scene_builder/resources/mecoffe-embed-v1/'
JSON_FILES = ('contract.json', 'contract-v2.json', 'issue_messages.json')


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def json_bytes(value):
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2, allow_nan=False)+'\n').encode('utf-8')


def lf(raw):
    return raw.replace(b'\r\n', b'\n')


def input_paths():
    return [*(SERVICE+name+'.py' for name in MODULES),
            *(SERVICE+name for name in JSON_FILES), 'adapter/scene_builder/asset_library.py',
            ASSETS+'asset-library.json', ASSETS+'catalog.json', 'NOTICE.md']


def source_revision(root):
    return subprocess.check_output(['git', '-C', str(root), 'log', '-1', '--format=%H', '--', *input_paths()],
                                   encoding='utf-8').strip()


def runtime_module(name, raw):
    text = lf(raw).decode('utf-8')
    if name in ('maps', 'checker'):
        old = 'from adapter.scene_builder.asset_library import published_asset_library'
        if text.count(old) != 1:
            raise ValueError(f'{name}: expected exactly one asset-library import; review the export recipe')
        text = text.replace(old, 'from ._asset_library import published_asset_library')
    if name == 'auto_evidence':
        # Keep existing pure compiler dependencies verbatim; remove review/file preparation only.
        tree = ast.parse(text)
        removed = set()
        for node in tree.body:
            if (isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and
                    node.name in ('prepare_ai_review', 'default_rules')) or (
                    isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == 'RULES_PATH'
                                                       for t in node.targets)):
                removed.update(range(node.lineno, node.end_lineno+1))
        text = ''.join(line for number, line in enumerate(text.splitlines(keepends=True), 1) if number not in removed)
        text = text.rstrip('\n')+'\n'
    # A new source import must not quietly introduce a dependency on the source repository.
    for node in ast.walk(ast.parse(text)):
        if isinstance(node, ast.ImportFrom) and node.module and node.module.split('.')[0] == 'adapter':
            raise ValueError(f'{name}: unexpected adapter import')
        if isinstance(node, ast.Import) and any(n.name.split('.')[0] == 'adapter' for n in node.names):
            raise ValueError(f'{name}: unexpected adapter import')
    return text.encode('utf-8')


